#!/usr/bin/env python3
"""Generate roms_data.h from the ROM images shipped in the beebjit tree.

Usage: python3 gen_roms.py <beebjit-dir> <output-header>
"""
import pathlib
import sys

ROMS = {
    # Model B
    "os12_rom": "os12.rom",
    "basic_rom": "basic.rom",
    "dfs09_rom": "DFS-0.9.rom",
    "dfs226_rom": "DFS226",
    # Master 128, MOS 3.20 (slot layout follows beebjit's config.c)
    "mos320_mos_rom": "mos3.20/mos.rom",
    "mos320_dfs_rom": "mos3.20/dfs.rom",
    "mos320_viewsht_rom": "mos3.20/viewsht.rom",
    "mos320_edit_rom": "mos3.20/edit.rom",
    "mos320_basic4_rom": "mos3.20/basic4.rom",
    "mos320_adfs_rom": "mos3.20/adfs.rom",
    "mos320_view_rom": "mos3.20/view.rom",
    "mos320_terminal_rom": "mos3.20/terminal.rom",
}


def main():
    beebjit = pathlib.Path(sys.argv[1])
    out = pathlib.Path(sys.argv[2])
    lines = ["/* Generated by gen_roms.py from beebjit/roms; do not edit. */",
             "#include <stdint.h>"]
    for name, fn in ROMS.items():
        data = (beebjit / "roms" / fn).read_bytes()
        data = data + bytes(16384 - len(data)) if len(data) < 16384 else data[:16384]
        lines.append("static const uint8_t %s[16384] = {" % name)
        for i in range(0, len(data), 16):
            lines.append("  " + ",".join("0x%02x" % b for b in data[i:i + 16]) + ",")
        lines.append("};")
    out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
